values (1, 'Main', 'USD', 'America/Los_Angeles')
on conflict (id) do nothing;

-- Lock down the auto-generated REST API. The app talks to Supabase only through
-- Next.js route handlers using the service-role key, which bypasses RLS. With RLS
-- on and no policies, the anon/public key can read/write nothing.
alter table account      enable row level security;
alter table settings     enable row level security;
alter table import_batch enable row level security;
alter table trade        enable row level security;
alter table execution    enable row level security;
alter table tag          enable row level security;
alter table trade_tag    enable row level security;
alter table day_journal  enable row level security;
alter table day_media    enable row level security;
